import { supabase } from '@/integrations/supabase/client';

export interface WikiSection {
  heading: string;
  content: string;
  keyPoints: string[];
  citations: string[];
  criticalPerspectives?: string[];
}
export interface WikiGlossaryItem { term: string; definition: string }
export interface WikiData {
  title: string;
  summary: string;
  readingTimeMinutes: number;
  difficulty?: 'Beginner' | 'Intermediate' | 'Advanced';
  cognitiveLevel?: 'Basic' | 'Standard' | 'Advanced';
  sections: WikiSection[];
  relatedTopics: string[];
  glossary?: WikiGlossaryItem[];
}
export type CognitiveLevel = 'Basic' | 'Standard' | 'Advanced';
export interface WikiHistoryItem { id: string; createdAt: number; wiki: WikiData }
export interface ChatMessage { role: 'user' | 'assistant'; content: string }

async function call<T>(body: Record<string, unknown>): Promise<T> {
  const { data, error } = await supabase.functions.invoke('tinywiki', { body });
  if (error) throw new Error(error.message || 'Request failed');
  if (data?.error) throw new Error(data.error);
  return data as T;
}

export const generateWiki = (topic: string, material: string, level: CognitiveLevel) =>
  call<{ wiki: WikiData; truncated?: boolean }>({ action: 'generate', topic, material, level });

export const chatWithWiki = (messages: ChatMessage[], wiki: WikiData) =>
  call<{ text: string }>({ action: 'chat', messages, wiki: { title: wiki.title, summary: wiki.summary, sections: wiki.sections } });

export const getEli5 = (term: string, context: string) =>
  call<{ text: string }>({ action: 'eli5', term, context });

// ── Library (localStorage) ────────────────────────────────────────────────
const HISTORY_KEY = 'uisu_tinywiki_history';
const MAX_HISTORY = 30;

export const loadHistory = (): WikiHistoryItem[] => {
  try { return JSON.parse(localStorage.getItem(HISTORY_KEY) || '[]'); } catch { return []; }
};
const saveHistory = (items: WikiHistoryItem[]) => {
  try { localStorage.setItem(HISTORY_KEY, JSON.stringify(items.slice(0, MAX_HISTORY))); } catch { /* quota */ }
};
export const addToHistory = (wiki: WikiData): WikiHistoryItem[] => {
  const item: WikiHistoryItem = { id: crypto.randomUUID(), createdAt: Date.now(), wiki };
  const next = [item, ...loadHistory()];
  saveHistory(next);
  return next.slice(0, MAX_HISTORY);
};
export const removeFromHistory = (id: string): WikiHistoryItem[] => {
  const next = loadHistory().filter((i) => i.id !== id);
  saveHistory(next);
  return next;
};
export const clearHistory = () => localStorage.removeItem(HISTORY_KEY);

// ── Share links: whole wiki encoded in the URL (UTF-8 safe base64) ────────
export const encodeWiki = (wiki: WikiData): string => {
  const bytes = new TextEncoder().encode(JSON.stringify(wiki));
  let bin = '';
  bytes.forEach((b) => (bin += String.fromCharCode(b)));
  return encodeURIComponent(btoa(bin));
};
export const decodeWiki = (encoded: string): WikiData | null => {
  try {
    const bin = atob(decodeURIComponent(encoded));
    const bytes = Uint8Array.from(bin, (c) => c.charCodeAt(0));
    const wiki = JSON.parse(new TextDecoder().decode(bytes));
    return wiki && typeof wiki.title === 'string' && Array.isArray(wiki.sections) ? wiki : null;
  } catch { return null; }
};

// ── Markdown export ───────────────────────────────────────────────────────
export const wikiToMarkdown = (d: WikiData): string => {
  const L: string[] = [`# ${d.title}`, ''];
  L.push(`> ${d.difficulty ? `**Difficulty:** ${d.difficulty} | ` : ''}**Reading time:** ${d.readingTimeMinutes} min`, '');
  L.push('## Summary', '', d.summary, '', '---', '');
  d.sections.forEach((s, i) => {
    L.push(`## ${String(i + 1).padStart(2, '0')}. ${s.heading}`, '', s.content, '');
    if (s.keyPoints?.length) L.push('### Key Points', '', ...s.keyPoints.map((p) => `- ${p}`), '');
    if (s.criticalPerspectives?.length) L.push('### Critical Perspectives', '', ...s.criticalPerspectives.map((p) => `- ${p}`), '');
    if (s.citations?.length) L.push('### Sources', '', ...s.citations.map((c) => `- ${c}`), '');
    L.push('---', '');
  });
  if (d.glossary?.length) {
    L.push('## Glossary', '');
    [...d.glossary].sort((a, b) => a.term.localeCompare(b.term)).forEach((g) => L.push(`**${g.term}**: ${g.definition}`, ''));
  }
  if (d.relatedTopics?.length) L.push('## Related Topics', '', ...d.relatedTopics.map((t) => `- ${t}`), '');
  L.push('---', '*Generated by UISU TinyWiki*');
  return L.join('\n');
};

export const downloadMarkdown = (d: WikiData) => {
  const url = URL.createObjectURL(new Blob([wikiToMarkdown(d)], { type: 'text/markdown;charset=utf-8' }));
  const a = document.createElement('a');
  a.href = url;
  a.download = `${d.title.replace(/[^a-z0-9]/gi, '_').toLowerCase()}.md`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
};
